_PIXMAP_CACHE = {}
_ICON_CACHE = {}


def clear_icon_cache():
    """Clear cached pixmaps and icons when theme changes."""
    _PIXMAP_CACHE.clear()
    _ICON_CACHE.clear()


def get_svg_string(name: str, color: str = None, stroke_width: float = 2.0) -> str:
    """Generate complete SVG XML string."""
    if color is None:
        color = COLORS.get("text_primary", "#FFFFFF")
    inner = SVG_PATHS.get(name, SVG_PATHS["notes"])
    # Replace fill="currentColor" with exact color
    inner = inner.replace('fill="currentColor"', f'fill="{color}"')
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" '
        f'fill="none" stroke="{color}" stroke-width="{stroke_width}" stroke-linecap="round" stroke-linejoin="round">'
        f'{inner}'
        f'</svg>'
    )


def get_pixmap(name: str, color: str = None, size: int = 20, stroke_width: float = 2.0, scale_factor: float = 4.0) -> QPixmap:
    """Return a razor-sharp vector-rendered QPixmap with 4x supersampling and setDevicePixelRatio."""
    if color is None:
        color = COLORS.get("text_primary", "#FFFFFF")
    cache_key = (name, color, size, stroke_width, scale_factor)
    if cache_key in _PIXMAP_CACHE:
        return _PIXMAP_CACHE[cache_key]

    svg_str = get_svg_string(name, color, stroke_width)
    data = QByteArray(svg_str.encode("utf-8"))
    renderer = QSvgRenderer(data)

    phys_size = max(1, int(round(size * scale_factor)))
    pixmap = QPixmap(phys_size, phys_size)
    pixmap.fill(QColor(0, 0, 0, 0))

    painter = QPainter(pixmap)
    painter.setRenderHint(QPainter.RenderHint.Antialiasing, True)
    painter.setRenderHint(QPainter.RenderHint.SmoothPixmapTransform, True)
    renderer.render(painter)
    painter.end()

    pixmap.setDevicePixelRatio(scale_factor)
    _PIXMAP_CACHE[cache_key] = pixmap
    return pixmap


def get_icon(name: str, color: str = None, size: int = 20, stroke_width: float = 2.0) -> QIcon:
    """Return a multi-resolution, high-DPI QIcon generated from SVG vector paths."""
    if color is None:
        color = COLORS.get("text_primary", "#FFFFFF")
    cache_key = (name, color, stroke_width)
    if cache_key in _ICON_CACHE:
        return _ICON_CACHE[cache_key]

    svg_str = get_svg_string(name, color, stroke_width)
    data = QByteArray(svg_str.encode("utf-8"))
    renderer = QSvgRenderer(data)

    icon = QIcon()
    # Multi-resolution support: gives Qt the exact crisp resolution for 100%, 125%, 150%, 200%, 300% DPI
    for s in (16, 20, 24, 32, 40, 48, 64, 96, 128, 256):
        pm = QPixmap(s, s)
        pm.fill(QColor(0, 0, 0, 0))
        painter = QPainter(pm)
        painter.setRenderHint(QPainter.RenderHint.Antialiasing, True)
        painter.setRenderHint(QPainter.RenderHint.SmoothPixmapTransform, True)
        renderer.render(painter)
        painter.end()
        icon.addPixmap(pm)

    _ICON_CACHE[cache_key] = icon
    return icon


def export_all_svgs(target_dir: str = "assets/icons"):
    """Save all SVGs as files in target directory for direct embedding / inspecting."""
    os.makedirs(target_dir, exist_ok=True)
    for name in SVG_PATHS:
        svg_content = get_svg_string(name, "#FFFFFF")
        path = os.path.join(target_dir, f"{name}.svg")
        with open(path, "w", encoding="utf-8") as f:
            f.write(svg_content)
